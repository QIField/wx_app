/** 名称 → 资源序号。 */
export const FACE_INDEX = Object.fromEntries(WX_FACES.map((n, i) => [n, i]))

/** 表情资源地址（public/wx-faces，构建时原样拷贝到 dist，离线可用）。 */
export function faceUrlOf(name) {
  const i = FACE_INDEX[name]
  return `${import.meta.env.BASE_URL}wx-faces/${i}.png`
}

